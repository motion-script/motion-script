// Generate the static registry `ms add <component>` reads.
//
// Follows shadcn/ui's own registry protocol (verified against their published
// schema — see packages/cli/src/registry/schema.ts, which this output must
// stay in step with):
//   GET <registryBase>/registry.json   → index: [{ name, type, description }]
//   GET <registryBase>/<name>.json     → full item: dependencies + files
//
// This is shadcn's own recommended way to self-host a custom registry: plain
// static JSON under public/r/, served by whatever already serves the rest of
// this site (motionscript.dev/r/...) — no separate hosting infrastructure.
//
// Output is gitignored: it is derived from source and regenerated by prebuild.

import fs from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"

const siteRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")
const repoRoot = path.resolve(siteRoot, "..", "..")
const outDir = path.join(process.cwd(), "public", "r")

/** One registry item per publishable @motion-script/* component package. */
const COMPONENTS = ["code", "latex"]

function assertExists(dir, label) {
  if (!fs.existsSync(dir)) {
    console.error(`[build:registry] ${label} not found at ${dir}. Run this from packages/site with the full repo checked out.`)
    process.exit(1)
  }
}

/**
 * Every real source `.ts` file under a component's `src/`, as paths relative
 * to `src/` (posix separators). Recurses into nested folders (defensively —
 * both current components are flat) but never into a `tests`/`test`
 * directory, and never matches `*.test.ts`, mirroring what the CLI's own
 * registry item `files` are meant to contain.
 */
function listSourceFiles(dir, baseDir = dir) {
  const entries = fs.readdirSync(dir, { withFileTypes: true })
  const files = []
  for (const entry of entries) {
    const fullPath = path.join(dir, entry.name)
    if (entry.isDirectory()) {
      if (entry.name === "tests" || entry.name === "test") continue
      files.push(...listSourceFiles(fullPath, baseDir))
      continue
    }
    if (!entry.name.endsWith(".ts") || entry.name.endsWith(".test.ts")) continue
    files.push(path.relative(baseDir, fullPath).split(path.sep).join("/"))
  }
  return files.sort((a, b) => a.localeCompare(b))
}

/**
 * Translate a `workspace:` protocol range (pnpm-only, meaningless outside
 * this monorepo) to what pnpm itself would substitute at publish time: the
 * dependency's own current version, with the workspace range's operator
 * carried over (`workspace:^` → `^1.2.3`, `workspace:*` → `1.2.3` exact).
 * Needed because `@motion-script/code`/`@motion-script/latex` declare
 * `@motion-script/core` as a *peer* dependency (satisfied via `motion-script`
 * in the monorepo) — once their source is copied into a project that only
 * depends on `motion-script`, that peer becomes a real, missing dependency
 * unless the registry item says so explicitly.
 */
function resolveDependencyRange(depName, range) {
  if (!range.startsWith("workspace:")) return range
  const dirName = depName.replace(/^@motion-script\//, "")
  const depPkg = JSON.parse(fs.readFileSync(path.join(repoRoot, "packages", dirName, "package.json"), "utf8"))
  const operator = range.slice("workspace:".length)
  return operator === "*" || operator === "" ? depPkg.version : `${operator}${depPkg.version}`
}

function buildItem(name) {
  const pkgDir = path.join(repoRoot, "packages", "components", name)
  const srcDir = path.join(pkgDir, "src")
  const pkg = JSON.parse(fs.readFileSync(path.join(pkgDir, "package.json"), "utf8"))

  // peerDependencies first: the framework dependency (@motion-script/core)
  // the copied source needs to resolve at all, ahead of the feature-specific
  // third-party packages (lezer grammars, MathJax, ...).
  const allDependencies = { ...pkg.peerDependencies, ...pkg.dependencies }
  const dependencies = Object.entries(allDependencies).map(
    ([dep, range]) => `${dep}@${resolveDependencyRange(dep, range)}`,
  )
  const files = listSourceFiles(srcDir).map((relPath) => ({
    path: relPath,
    content: fs.readFileSync(path.join(srcDir, relPath), "utf8"),
  }))

  return {
    name,
    type: "registry:component",
    description: pkg.description,
    dependencies,
    files,
  }
}

// ── Generate ─────────────────────────────────────────────────────────────────

for (const name of COMPONENTS) {
  assertExists(path.join(repoRoot, "packages", "components", name, "src"), `${name} component source`)
}

fs.mkdirSync(outDir, { recursive: true })

const index = []
for (const name of COMPONENTS) {
  const item = buildItem(name)
  fs.writeFileSync(path.join(outDir, `${name}.json`), JSON.stringify(item, null, 2))
  index.push({ name: item.name, type: item.type, description: item.description })
  console.log(`[build:registry] ${name}: ${item.files.length} files, ${item.dependencies.length} dependencies`)
}

fs.writeFileSync(path.join(outDir, "registry.json"), JSON.stringify(index, null, 2))
console.log(`[build:registry] ${index.length} components written to ${path.relative(siteRoot, outDir)}`)
