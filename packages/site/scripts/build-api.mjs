// Generate the API reference the /api routes render.
//
// `lib/api.ts` reads a typedoc-markdown tree: one folder per package, each with
// an `index.md` package index, kind folders (`classes/`, `functions/`, …) of
// pages, and a `typedoc-sidebar.cjs` describing the navigation. Everything to
// render that already existed; the tree itself did not, because
// `versionApiDir()` pointed at a `packages/old-site/api` directory this repo
// does not have, so `/api/core` was never generated and the nav link 404'd.
//
// typedoc reads the packages' TypeScript source (no build needed) and emits the
// markdown; the sidebar is synthesised here by walking that output, so nothing
// depends on a plugin-specific sidebar feature.
//
// Output is gitignored: it is derived from source and regenerated by prebuild.

import { spawnSync } from "node:child_process"
import fs from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"

const siteRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")
const repoRoot = path.resolve(siteRoot, "..", "..")
const outRoot = path.join(siteRoot, "content", "api")

/** typedoc treats `entryPoints` as globs, where a backslash is an escape. */
const posix = (p) => p.split(path.sep).join("/")

/** Must stay in step with `PACKAGES_BY_VERSION.default` in lib/api.ts. */
const PACKAGES = [
  { pkg: "core", dir: "packages/core" },
  { pkg: "code", dir: "packages/components/code" },
  { pkg: "latex", dir: "packages/components/latex" },
]

const typedocBin = path.join(repoRoot, "node_modules", "typedoc", "bin", "typedoc")
if (!fs.existsSync(typedocBin)) {
  console.error(
    `[build:api] typedoc is not installed at ${repoRoot}. Run \`pnpm install\` there.`,
  )
  process.exit(1)
}

// ── Sidebar ──────────────────────────────────────────────────────────────────

/** "type-aliases" → "Type Aliases", "classes" → "Classes". */
function labelFor(folder) {
  // A scoped-package folder (`@motion-script`) is a real name, not a phrase to
  // title-case; it only ever wraps a namespace, and `collapse` drops it anyway.
  if (folder.startsWith("@")) return folder
  return folder
    .split("-")
    .map((word) => word.charAt(0).toUpperCase() + word.slice(1))
    .join(" ")
}

/**
 * Fold a category that holds nothing but one other category into it, so a
 * namespace surfaces as `JSX` rather than `@motion-script > Namespaces > JSX`.
 * The wrapper folders typedoc emits for those carry no pages of their own.
 */
function collapse(items) {
  return items.map((item) => {
    if (item.type !== "category") return item
    let node = { ...item, items: collapse(item.items) }
    while (!node.link && node.items.length === 1 && node.items[0].type === "category") {
      node = node.items[0]
    }
    return node
  })
}

/**
 * Build the `RawItem[]` lib/api.ts expects from the emitted files. `id` is the
 * page's path relative to content/api (so it starts with the package folder),
 * which is exactly what `idToSlug` turns into a URL.
 */
function buildSidebar(dir, idPrefix) {
  const entries = fs.readdirSync(dir, { withFileTypes: true })
  const items = []

  for (const entry of entries.filter((e) => e.isDirectory()).sort((a, b) => a.name.localeCompare(b.name))) {
    const childDir = path.join(dir, entry.name)
    const childId = `${idPrefix}/${entry.name}`
    const children = buildSidebar(childDir, childId)
    if (children.length === 0) continue
    const hasIndex = fs.existsSync(path.join(childDir, "index.md"))
    items.push({
      type: "category",
      label: labelFor(entry.name),
      items: children,
      ...(hasIndex ? { link: { type: "doc", id: `${childId}/index` } } : {}),
    })
  }

  for (const entry of entries.filter((e) => e.isFile() && e.name.endsWith(".md")).sort((a, b) => a.name.localeCompare(b.name))) {
    // The folder's own index is reached through the category link above, not as
    // a sibling entry, so it must not appear twice.
    if (entry.name === "index.md") continue
    const stem = entry.name.slice(0, -3)
    items.push({ type: "doc", id: `${idPrefix}/${stem}`, label: stem })
  }

  return items
}

function writeSidebar(pkg) {
  const dir = path.join(outRoot, pkg)
  const items = collapse(buildSidebar(dir, pkg))
  const source =
    "// Generated by scripts/build-api.mjs. Do not edit.\n" +
    `const typedocSidebar = { items: ${JSON.stringify(items, null, 2)} };\n` +
    "module.exports = typedocSidebar.items;\n"
  fs.writeFileSync(path.join(dir, "typedoc-sidebar.cjs"), source, "utf8")
  return items
}

// ── Generate ─────────────────────────────────────────────────────────────────

fs.rmSync(outRoot, { recursive: true, force: true })

let total = 0
for (const { pkg, dir } of PACKAGES) {
  const entry = path.join(repoRoot, dir, "src", "index.ts")
  if (!fs.existsSync(entry)) {
    console.error(`[build:api] no entry point at ${entry}`)
    process.exit(1)
  }

  const result = spawnSync(
    process.execPath,
    [
      typedocBin,
      "--plugin", "typedoc-plugin-markdown",
      "--entryPoints", posix(entry),
      "--tsconfig", path.join(repoRoot, dir, "tsconfig.build.json"),
      "--out", path.join(outRoot, pkg),
      // lib/api.ts resolves a package index as `<pkg>/index.md`.
      "--entryFileName", "index",
      "--readme", "none",
      "--githubPages", "false",
      // typedoc warns on every `{@link}` that points at a symbol outside the
      // entry point, which is hundreds of lines of noise for a build step that
      // still produces correct pages. Errors are still fatal below.
      "--logLevel", "Error",
    ],
    { cwd: repoRoot, stdio: "inherit" },
  )

  if (result.error || result.status !== 0) {
    console.error(`[build:api] typedoc failed for ${pkg}.`, result.error ?? "")
    process.exit(result.status || 1)
  }

  const items = writeSidebar(pkg)
  const count = fs.readdirSync(path.join(outRoot, pkg), { recursive: true }).filter((f) => String(f).endsWith(".md")).length
  total += count
  console.log(`[build:api] ${pkg}: ${count} pages, ${items.length} top-level sidebar entries`)
}

console.log(`[build:api] ${total} pages written to ${path.relative(siteRoot, outRoot)}`)
